-- YardLens PostgreSQL schema. Idempotent: safe to apply on every start (`nx run api:db-setup`).

CREATE TABLE IF NOT EXISTS cameras (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(120)     NOT NULL,
    source_type   varchar(16)      NOT NULL,
    url           varchar(2048)    NOT NULL,
    enabled       boolean          NOT NULL DEFAULT true,
    inference_fps double precision NOT NULL DEFAULT 3.0,
    line          jsonb,
    zone          jsonb,
    plate_url     varchar(2048),
    detection     jsonb,
    created_at    timestamptz      NOT NULL DEFAULT now(),
    updated_at    timestamptz      NOT NULL DEFAULT now(),
    CONSTRAINT uq_cameras_name UNIQUE (name),
    CONSTRAINT ck_cameras_source_type
        CHECK (source_type IN ('rtsp', 'http', 'hls', 'file')),
    CONSTRAINT ck_cameras_inference_fps CHECK (inference_fps > 0 AND inference_fps <= 15)
);

-- Added with loading bays: the area a vehicle parks in while it is loaded.
ALTER TABLE cameras ADD COLUMN IF NOT EXISTS zone jsonb;
-- Added with load balancing: the high-resolution main stream, opened only to read plates.
ALTER TABLE cameras ADD COLUMN IF NOT EXISTS plate_url varchar(2048);
-- Added with per-camera detection: a camera's own model, classes, cargo and confidence.
ALTER TABLE cameras ADD COLUMN IF NOT EXISTS detection jsonb;
-- Rows written before None was stored as SQL NULL hold the JSON value null instead, which
-- counted as "has a zone" in the loading summary.
UPDATE cameras SET line = NULL WHERE line = 'null'::jsonb;
UPDATE cameras SET zone = NULL WHERE zone = 'null'::jsonb;
UPDATE cameras SET detection = NULL WHERE detection = 'null'::jsonb;

CREATE TABLE IF NOT EXISTS events (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    camera_id     integer          NOT NULL REFERENCES cameras (id) ON DELETE CASCADE,
    type          varchar(32)      NOT NULL,
    class_name    varchar(64),
    tracker_id    integer,
    confidence    double precision,
    snapshot_path varchar(512),
    details       jsonb,
    created_at    timestamptz      NOT NULL DEFAULT now()
);

-- Recreated so databases created before the current set of event types learn about it.
-- Per-object "object_entered" events are no longer recorded: they were noise and disk.
DELETE FROM events WHERE type = 'object_entered';
ALTER TABLE events DROP CONSTRAINT IF EXISTS ck_events_type;
ALTER TABLE events ADD CONSTRAINT ck_events_type CHECK (
    type IN (
        'line_crossed_in', 'line_crossed_out',
        'camera_online', 'camera_offline', 'vehicle_arrived', 'loading_completed'
    )
);

-- YouTube sources were dropped (yt-dlp needed a JavaScript runtime and broke often).
DELETE FROM cameras WHERE source_type = 'youtube';
ALTER TABLE cameras DROP CONSTRAINT IF EXISTS ck_cameras_source_type;
ALTER TABLE cameras ADD CONSTRAINT ck_cameras_source_type
    CHECK (source_type IN ('rtsp', 'http', 'hls', 'file'));

CREATE INDEX IF NOT EXISTS ix_events_created_at ON events (created_at);
CREATE INDEX IF NOT EXISTS ix_events_camera_created ON events (camera_id, created_at);
CREATE INDEX IF NOT EXISTS ix_events_type_created ON events (type, created_at);

-- One row per vehicle loaded in a bay. Kept for reporting; event retention does not touch it.
CREATE TABLE IF NOT EXISTS loading_sessions (
    id                    varchar(32)      PRIMARY KEY,
    camera_id             integer          NOT NULL REFERENCES cameras (id) ON DELETE CASCADE,
    status                varchar(16)      NOT NULL,
    arrived_at            timestamptz      NOT NULL,
    departed_at           timestamptz,
    loading_started_at    timestamptz,
    loading_finished_at   timestamptz,
    loaded                integer          NOT NULL DEFAULT 0,
    unloaded              integer          NOT NULL DEFAULT 0,
    vehicle_class         varchar(64),
    plate                 varchar(16),
    plate_confidence      double precision,
    plate_corrected       boolean          NOT NULL DEFAULT false,
    vehicle_snapshot_path varchar(512),
    plate_snapshot_path   varchar(512),
    created_at            timestamptz      NOT NULL DEFAULT now(),
    updated_at            timestamptz      NOT NULL DEFAULT now(),
    CONSTRAINT ck_loading_sessions_status CHECK (status IN ('active', 'completed'))
);

CREATE INDEX IF NOT EXISTS ix_loading_sessions_arrived ON loading_sessions (arrived_at);
CREATE INDEX IF NOT EXISTS ix_loading_sessions_camera_arrived
    ON loading_sessions (camera_id, arrived_at);
CREATE INDEX IF NOT EXISTS ix_loading_sessions_plate ON loading_sessions (plate);

CREATE TABLE IF NOT EXISTS app_settings (
    key        varchar(64) PRIMARY KEY,
    value      jsonb       NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- The administrator. One row in practice; usernames are stored lower-cased.
CREATE TABLE IF NOT EXISTS users (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            varchar(64)  NOT NULL,
    password_hash       varchar(255) NOT NULL,
    password_changed_at timestamptz  NOT NULL DEFAULT now(),
    last_login_at       timestamptz,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_username UNIQUE (username)
);

-- Refresh tokens, stored as SHA-256 hashes. Every refresh rotates the token within its family
-- (one family per sign-in); a rotated token used again revokes the whole family.
CREATE TABLE IF NOT EXISTS refresh_tokens (
    id           varchar(32)  PRIMARY KEY,
    user_id      integer      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    family_id    varchar(32)  NOT NULL,
    token_hash   varchar(64)  NOT NULL,
    created_at   timestamptz  NOT NULL DEFAULT now(),
    expires_at   timestamptz  NOT NULL,
    last_used_at timestamptz,
    rotated_at   timestamptz,
    revoked_at   timestamptz,
    user_agent   varchar(256),
    ip           varchar(64),
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash)
);

CREATE INDEX IF NOT EXISTS ix_refresh_tokens_family ON refresh_tokens (family_id);
CREATE INDEX IF NOT EXISTS ix_refresh_tokens_user ON refresh_tokens (user_id);

-- Workers on other machines were dropped: one server runs every camera.
DROP TABLE IF EXISTS camera_assignments;
ALTER TABLE cameras DROP COLUMN IF EXISTS worker_id;
DROP TABLE IF EXISTS workers;

-- Every event carries an id of its own, so one a worker sends again after a dropped connection
-- is saved once.
ALTER TABLE events ADD COLUMN IF NOT EXISTS uid varchar(32);
CREATE UNIQUE INDEX IF NOT EXISTS uq_events_uid ON events (uid);
